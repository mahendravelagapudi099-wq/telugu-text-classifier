"""Produce reports/data_report.md from the processed splits.

Reports split sizes, class distribution, length statistics, Telugu-script
percentage, dedup counts, and sample rows per class.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from src.utils import load_config  # noqa: E402

TELUGU_RANGE = ("\u0C00", "\u0C7F")


def telugu_share(text: str) -> float:
    """Fraction of non-whitespace characters that are Telugu script."""
    chars = [c for c in text if not c.isspace()]
    if not chars:
        return 0.0
    telugu = sum(1 for c in chars if TELUGU_RANGE[0] <= c <= TELUGU_RANGE[1])
    return telugu / len(chars)


def length_table(parts: dict[str, pd.DataFrame]) -> str:
    lines = [
        "| split | n | chars mean | chars median | chars min-max | words mean | words median | Telugu chars % |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, df in parts.items():
        chars = df["text"].str.len()
        words = df["text"].str.split().str.len()
        overall_telugu = df["text"].map(telugu_share).mean() * 100
        lines.append(
            f"| {name} | {len(df)} | {chars.mean():.1f} | {chars.median():.0f} | "
            f"{chars.min()}-{chars.max()} | {words.mean():.1f} | {words.median():.0f} | "
            f"{overall_telugu:.1f}% |"
        )
    return "\n".join(lines)


def class_table(parts: dict[str, pd.DataFrame]) -> str:
    overall = pd.concat(parts.values())["label"]
    rows = ["| label | " + " | ".join(parts.keys()) + " | total | total % |",
            "|---" * (len(parts) + 3) + "|"]
    for label in sorted(overall.unique()):
        counts = [int((df["label"] == label).sum()) for df in parts.values()]
        total = sum(counts)
        rows.append(
            f"| {label} | " + " | ".join(str(c) for c in counts) + f" | {total} | "
            f"{total / len(overall) * 100:.1f}% |"
        )
    return "\n".join(rows)


def sample_rows(train: pd.DataFrame, n: int = 10) -> str:
    sections = []
    for label in sorted(train["label"].unique()):
        sample = train[train["label"] == label].sample(n=n, random_state=42)
        lines = [f"**{label}**", ""]
        for text in sample["text"]:
            shown = text if len(text) <= 120 else text[:120] + "…"
            lines.append(f"- {shown}")
        sections.append("\n".join(lines))
    return "\n\n".join(sections)


def main() -> None:
    cfg = load_config()
    processed = Path(cfg["paths"]["processed"])
    parts = {
        name: pd.read_csv(processed / f"{name}.csv")
        for name in ("train", "validation", "test")
    }
    summary = json.loads(Path(cfg["paths"]["results"], "data_summary.json").read_text(encoding="utf-8"))

    report = f"""# Data report — {summary['dataset']}

Generated by `scripts/analyze_data.py` from `data/processed/`.

## Cleaning summary

- Raw rows pooled from official train/validation/test: **{summary['rows_raw']}**
- Removed (empty/null after NFC cleaning): **{summary['empty_or_null_removed']}**
- Exact duplicates removed (after normalization): **{summary['exact_duplicates_removed']}**
- Near-duplicates removed (char-{summary['shingle_size']}-gram shingles, Jaccard >= {summary['jaccard_threshold']}, removed *before* splitting so no near-duplicate spans two splits): **{summary['near_duplicates_removed']}** in {summary['near_duplicate_groups']} groups
- Final rows: **{summary['rows_final']}**

Split seed: {summary['seed']}. Ratios: {summary['split_ratios'][0]}/{summary['split_ratios'][1]}/{summary['split_ratios'][2]}.

## Class distribution

{class_table(parts)}

## Text length and script statistics

{length_table(parts)}

## Sample rows per class (10 random from train, truncated to 120 chars)

{sample_rows(parts['train'])}
"""
    out = Path(cfg["paths"]["reports"]) / "data_report.md"
    out.write_text(report, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
